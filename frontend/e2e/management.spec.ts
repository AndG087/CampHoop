import { test, expect, type Page } from '@playwright/test'
import { readFileSync, existsSync, writeFileSync } from 'node:fs'
import { randomUUID } from 'node:crypto'

const envFile = new URL('../../backend/.env', import.meta.url)
const password = process.env.CAMPHOOP_TEST_PASSWORD ?? (existsSync(envFile) ? readFileSync(envFile, 'utf8').match(/^DEMO_PASSWORD=(.+)$/m)?.[1].trim() : undefined)
test.skip(!password, 'Configure a local backend test password')
async function login(page: Page, email = 'marina@camphoop.demo') {
  await page.goto('/login')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password!)
  await page.getByRole('button', { name: 'Entrar →', exact: true }).click()
  await expect(page.locator('.sidebar')).toBeVisible()
}

test('coach creates, edits and copies a private roster across seasons without losing history', async ({ page, browser }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await login(page)
  const original = await (await page.request.get('/api/auth/me')).json()
  const prefix = `CampHoop E2E ${randomUUID().replaceAll('-', '').slice(0, 12)}`
  const cleanup = new URL('../../backend/data/e2e-rosters.json', import.meta.url)
  const runs = existsSync(cleanup) ? JSON.parse(readFileSync(cleanup, 'utf8')) : []
  writeFileSync(cleanup, JSON.stringify([...runs, { prefix, userId: original.id, originalTeamId: original.teamId }]))
  try {
    await page.goto('/times')
    await page.getByRole('link', { name: '+ Criar equipe própria', exact: true }).click()
    const modal = page.getByRole('dialog', { name: 'Criar equipe própria' })
    await expect(modal).toBeVisible()
    await modal.getByLabel('Clube', { exact: true }).selectOption('new')
    await modal.getByLabel('Nome do clube', { exact: true }).fill(prefix)
    await modal.getByLabel('Sigla', { exact: true }).fill('CHT')
    await modal.getByLabel('Cidade', { exact: true }).fill('Campinas')
    await modal.getByLabel('Nome da equipe', { exact: true }).fill('Elenco inicial E2E')
    const created = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/management/teams' && r.request().method() === 'POST')
    await modal.getByRole('button', { name: 'Criar equipe', exact: true }).click()
    const team = await (await created).json()
    await expect(page.getByRole('heading', { name: 'Elenco inicial E2E', exact: true, level: 1 })).toBeVisible()
    await expect(page.getByRole('combobox', { name: 'Equipe de trabalho' })).toHaveValue(team.id)

    const teamProfile = await (await page.request.get(`/api/teams/${team.id}`)).json()
    const opponentResponse = await page.request.post('/api/management/teams', { data: { name: 'Adversário E2E', category: 'Sub-17', gender: 'Feminino', coach: 'Marina Costa', season: '2026/27', clubId: teamProfile.team.club.id, makeActive: false } })
    expect(opponentResponse.ok()).toBe(true)
    const opponent = await opponentResponse.json()
    await page.getByRole('button', { name: 'Acessos e autorizações', exact: true }).click()
    const access = page.getByRole('dialog', { name: 'Acessos e autorizações', exact: true })
    await expect(access).toContainText('Proprietário')
    await access.getByLabel('E-mail do técnico', { exact: true }).fill('missing-coach@camphoop.demo')
    await access.getByRole('button', { name: 'Conceder acesso', exact: true }).click()
    await expect(access.getByRole('alert')).toContainText('conta de técnico ativa')
    await access.getByRole('combobox', { name: 'Adversário', exact: true }).selectOption(opponent.id)
    await access.getByLabel('Data do amistoso', { exact: true }).fill('2026-11-15')
    await access.getByRole('button', { name: 'Autorizar participação', exact: true }).click()
    await expect(access.getByRole('list', { name: 'Autorizações concedidas', exact: true })).toContainText('Amistoso · 2026-11-15')
    await access.getByRole('button', { name: 'Revogar autorização', exact: true }).click()
    await expect(access.getByRole('button', { name: 'Revogar autorização', exact: true })).toHaveCount(0)
    await access.getByLabel('Fechar', { exact: true }).click()

    await page.getByRole('button', { name: 'Editar equipe', exact: true }).click()
    await page.getByRole('dialog').getByLabel('Nome da equipe', { exact: true }).fill('Elenco revisado E2E')
    await page.getByRole('dialog').getByRole('button', { name: 'Salvar equipe', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Elenco revisado E2E', exact: true, level: 1 })).toBeVisible()
    await page.getByRole('button', { name: '+ Adicionar atleta', exact: true }).click()
    const athleteForm = page.getByRole('dialog', { name: 'Adicionar atleta', exact: true })
    await athleteForm.getByLabel('Nome completo', { exact: true }).fill('Joana E2E')
    await athleteForm.getByLabel('Número da camisa', { exact: true }).fill('8')
    await athleteForm.getByLabel('Posição', { exact: true }).fill('Armadora')
    await athleteForm.getByLabel('Data de nascimento (privada)', { exact: true }).fill('2009-03-14')
    await athleteForm.getByLabel('Altura em centímetros', { exact: true }).fill('168')
    const registered = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/management/athletes' && r.request().method() === 'POST')
    await athleteForm.getByRole('button', { name: 'Cadastrar atleta', exact: true }).click()
    const athlete = await (await registered).json()
    await expect(page.getByRole('heading', { name: 'Joana E2E', exact: true }).first()).toBeVisible()
    await expect(page.locator('.facts')).toContainText('14 mar 2009')
    await page.getByRole('button', { name: 'Editar perfil', exact: true }).click()
    await page.getByRole('dialog').getByLabel('Número da camisa', { exact: true }).fill('11')
    await page.getByRole('dialog').getByRole('button', { name: 'Salvar atleta', exact: true }).click()
    await expect(page.locator('.athlete-card')).toContainText('#11')
    await page.reload()
    await expect(page.locator('.athlete-card')).toContainText('#11')

    const visitor = await browser.newContext()
    try {
      const publicProfile = await (await visitor.request.get(`http://localhost:5173/api/athletes/${athlete.id}`)).json()
      expect(publicProfile.private).toBeNull()
      expect(publicProfile.age).toBeGreaterThan(0)
      const basic = await visitor.newPage()
      await login(basic, 'joao@camphoop.demo')
      await basic.goto(`/atletas/${athlete.id}`)
      await expect(basic.locator('.facts')).not.toContainText('14 mar 2009')
      await expect(basic.getByRole('button', { name: 'Editar perfil', exact: true })).toHaveCount(0)
    } finally { await visitor.close() }

    await page.goto(`/times/${team.id}`)
    await page.getByRole('button', { name: 'Nova temporada', exact: true }).click()
    const future = page.getByRole('dialog', { name: 'Preparar nova temporada' })
    await future.getByLabel('Nova temporada', { exact: true }).fill('2027/28')
    await future.getByLabel('Nome da equipe', { exact: true }).fill('Elenco 2027 E2E')
    await future.getByRole('button', { name: 'Criar temporada', exact: true }).click()
    await expect(page.getByRole('combobox', { name: 'Temporada', exact: true })).toHaveValue('2027/28')
    await expect(page.getByRole('heading', { name: 'Elenco 2027 E2E', exact: true, level: 1 })).toBeVisible()
    await expect(page.getByRole('status')).toContainText('1 atletas copiados')
    await expect(page.locator('.roster')).toContainText('Joana E2E')
    const old = await (await page.request.get(`/api/teams/${team.id}?season=2026/27`)).json()
    const next = await (await page.request.get(`/api/teams/${team.id}?season=2027/28`)).json()
    expect(old.team.name).toBe('Elenco revisado E2E')
    expect(old.roster[0].id).toBe(athlete.id)
    expect(next.roster[0].id).not.toBe(athlete.id)
    expect(next.roster[0].games).toBe(0)
    await page.getByRole('link', { name: /Joana E2E/ }).click()
    await page.getByRole('button', { name: 'Editar perfil', exact: true }).click()
    await page.getByRole('dialog').getByLabel('Número da camisa', { exact: true }).fill('23')
    await page.getByRole('dialog').getByRole('button', { name: 'Salvar atleta', exact: true }).click()
    await expect(page.locator('.athlete-card')).toContainText('#23')
    expect((await (await page.request.get(`/api/athletes/${athlete.id}`)).json()).number).toBe(11)
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await page.screenshot({ path: 'test-results/roster-management-mobile.png', fullPage: true })
    expect(errors).toEqual([])
    await page.getByRole('button', { name: 'Excluir vínculo sem histórico', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Confirmar exclusão', exact: true }).click()
    await expect(page).toHaveURL(/\/atletas$/)
    await page.goto(`/times/${team.id}`)
    await page.getByRole('button', { name: 'Excluir temporada vazia', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Confirmar exclusão', exact: true }).click()
    await expect(page).toHaveURL(/\/times$/)
    await expect(page.getByRole('combobox', { name: 'Temporada', exact: true })).toHaveValue('2026/27')
    await page.goto(`/times/${opponent.id}`)
    await page.getByRole('button', { name: 'Excluir equipe vazia', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Confirmar exclusão', exact: true }).click()
    await expect(page).toHaveURL(/\/times$/)
  } finally {
    await page.request.post('/api/auth/login', { data: { email: 'marina@camphoop.demo', password } })
    if (original.teamId) await page.request.post('/api/management/active-team', { data: { teamId: original.teamId } })
  }
})
